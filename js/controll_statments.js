const month = "march"
switch (month) {
    case "January":
        console.log(1);
        break;
    case "feb":
        console.log(2);
        break;
    case 'march':
        console.log(3);
        break;
    case "april":
        console.log(4);
        break;
    default:
        console.log(5);
        break;
}